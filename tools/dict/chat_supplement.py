def iter_words():
    """展开 GROUPS，产出 (word, freq, flags)。

    `词@倍数` 语法用于个体加权；同一词重复出现会各产出一条，由调用方累加。
    """
    for flags, base, text in GROUPS:
        for token in text.split():
            token = token.strip()
            if not token:
                continue
            mult = 1.0
            if "@" in token:
                word, _, times = token.partition("@")
                try:
                    mult = float(times)
                except ValueError:
                    mult = 1.0
                token = word
            if not token:
                continue
            yield token, int(round(base * mult)), flags


