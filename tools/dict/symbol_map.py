def iter_symbols():
    """产出 (pinyin_alias, symbol, flags, freq)。"""
    for alias, flags, freq, symbols in EMOJI_GROUPS + PUNCT_GROUPS:
        for sym in symbols.split():
            yield alias, sym, flags, freq


